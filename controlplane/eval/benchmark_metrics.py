"""Ranking and threshold metrics for comparing against published detector scores.

These were previously computed in throwaway scripts, which meant the numbers quoted in the
README could not be regenerated by any committed command. They live here so that every
benchmark figure this project publishes comes out of `make`.

Tie handling is the thing to be careful about. Our Tier 0 and Tier 1 detectors are lexical
and emit long runs of identical scores, so a metric that breaks ties optimistically flatters
them substantially. Everything here uses mid-ranks or the pessimistic convention.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import isnan


def _mid_ranks(values: list[float]) -> list[float]:
    """Average ranks within each tie group, 1-based."""
    order = sorted(range(len(values)), key=lambda index: values[index])
    ranks = [0.0] * len(values)
    position = 0
    while position < len(order):
        end = position
        while end + 1 < len(order) and values[order[end + 1]] == values[order[position]]:
            end += 1
        shared = (position + end) / 2.0 + 1.0
        for index in order[position : end + 1]:
            ranks[index] = shared
        position = end + 1
    return ranks


def rank_auc(labels: list[bool], scores: list[float]) -> float:
    """Mann-Whitney U as a proportion. NaN when one class is absent."""
    if len(labels) != len(scores):
        raise ValueError("labels and scores must be the same length")
    positives = sum(labels)
    negatives = len(labels) - positives
    if positives == 0 or negatives == 0:
        return float("nan")
    ranks = _mid_ranks(scores)
    positive_rank_sum = sum(
        rank for rank, label in zip(ranks, labels, strict=True) if label
    )
    return (positive_rank_sum - positives * (positives + 1) / 2) / (positives * negatives)


def average_precision(labels: list[bool], scores: list[float]) -> float:
    """AUPRC by the step-wise estimator sklearn calls `average_precision_score`.

    Ties are pooled: every row at a given score is admitted together, so a detector cannot
    be credited with an ordering it did not produce. This is what makes the number
    comparable with published AUPRC on the same benchmark.
    """
    if len(labels) != len(scores):
        raise ValueError("labels and scores must be the same length")
    positives = sum(labels)
    if positives == 0:
        return float("nan")
    order = sorted(range(len(scores)), key=lambda index: -scores[index])
    total = 0.0
    seen = 0
    hits = 0
    previous_recall = 0.0
    position = 0
    while position < len(order):
        end = position
        while end + 1 < len(order) and scores[order[end + 1]] == scores[order[position]]:
            end += 1
        for index in order[position : end + 1]:
            seen += 1
            hits += labels[index]
        recall = hits / positives
        precision = hits / seen
        total += precision * (recall - previous_recall)
        previous_recall = recall
        position = end + 1
    return total


@dataclass(frozen=True)
class OperatingPoint:
    """One threshold and what it does, on whichever split it was measured."""

    threshold: float
    precision: float
    recall: float
    f1: float
    false_positive_rate: float
    flagged: int

    total: int = 0

    @property
    def is_degenerate(self) -> bool:
        """Flags everything or nothing, so the F1 describes the corpus, not the detector.

        Worth stating explicitly because on a high-base-rate corpus a flag-everything policy
        scores a respectable-looking F1: at Aegis's 66% base rate it is 0.796, which is
        higher than the 0.62 published for Llama Guard Base. Our lexical Tier 0/Tier 1
        flagged 100% of Aegis rows and scored 0.7956 -- the null exactly, to four decimals --
        and without this check that would have been reported as a result.
        """
        return self.flagged == 0 or self.flagged == self.total


def operating_point(
    labels: list[bool], scores: list[float], threshold: float
) -> OperatingPoint:
    flagged = [score >= threshold for score in scores]
    true_positives = sum(a and b for a, b in zip(labels, flagged, strict=True))
    false_positives = sum((not a) and b for a, b in zip(labels, flagged, strict=True))
    positives = sum(labels)
    negatives = len(labels) - positives
    precision = true_positives / (true_positives + false_positives) if any(flagged) else 0.0
    recall = true_positives / positives if positives else 0.0
    f1 = (
        2 * precision * recall / (precision + recall)
        if (precision + recall) > 0
        else 0.0
    )
    return OperatingPoint(
        threshold=threshold,
        precision=precision,
        recall=recall,
        f1=f1,
        false_positive_rate=false_positives / negatives if negatives else 0.0,
        flagged=sum(flagged),
        total=len(labels),
    )


def flag_everything_f1(labels: list[bool]) -> float:
    """The F1 a detector gets by flagging every row: 2p/(1+p) at base rate p.

    The honest null for any F1 quoted on an imbalanced corpus. An F1 below this is worse
    than no detector at all, and one barely above it is not evidence of much.
    """
    if not labels:
        return float("nan")
    base_rate = sum(labels) / len(labels)
    return 2 * base_rate / (1 + base_rate) if base_rate > 0 else 0.0


def best_f1_threshold(labels: list[bool], scores: list[float]) -> float:
    """The F1-maximising threshold *on the split it is given*.

    Call this on calibration and apply the result to test. Calling it on test and quoting the
    F1 is an oracle threshold, which is not what published fixed-operating-point numbers are,
    and every report here must say which of the two it is showing.
    """
    if not scores:
        raise ValueError("need at least one score")
    best = max(
        (operating_point(labels, scores, candidate) for candidate in sorted(set(scores))),
        key=lambda point: point.f1,
    )
    return best.threshold


def spearman(left: list[float], right: list[float]) -> float:
    """Rank correlation via Pearson on mid-ranks. No scipy in this project."""
    if len(left) != len(right):
        raise ValueError("inputs must be the same length")
    if len(left) < 2:
        return float("nan")
    ranked_left = _mid_ranks(left)
    ranked_right = _mid_ranks(right)
    count = float(len(left))
    mean_left = sum(ranked_left) / count
    mean_right = sum(ranked_right) / count
    covariance = sum(
        (a - mean_left) * (b - mean_right)
        for a, b in zip(ranked_left, ranked_right, strict=True)
    )
    variance_left = sum((a - mean_left) ** 2 for a in ranked_left)
    variance_right = sum((b - mean_right) ** 2 for b in ranked_right)
    if variance_left <= 0 or variance_right <= 0:
        # A constant on either side has no ranking to correlate. Reported as NaN rather
        # than as 1.0, which is what an undefined correlation silently looks like.
        return float("nan")
    return float(covariance / (variance_left**0.5 * variance_right**0.5))


def within_band(value: float, low: float, high: float) -> bool:
    """Whether a measured value sits inside a published range, NaN-safe."""
    return not isnan(value) and low <= value <= high


def false_positive_rate_at_recall(
    labels: list[bool], scores: list[float], target_recall: float
) -> tuple[float, float]:
    """The cheapest false-positive rate that still reaches `target_recall`.

    Fixed-operating-point baselines publish one (false-refusal, catch) pair each. A system
    with an adjustable threshold cannot be compared to that from its own operating point
    alone, so this matches one axis and reads off the other.

    The threshold is chosen on the split it is measured on, which makes this an **oracle**
    comparison and it must be reported as one. Returns (rate, threshold); the rate is NaN
    when the target recall is unreachable.
    """
    positives = sum(labels)
    negatives = len(labels) - positives
    if positives == 0 or negatives == 0:
        return float("nan"), float("nan")
    best = float("nan")
    chosen = float("nan")
    for candidate in sorted(set(scores)):
        point = operating_point(labels, scores, candidate)
        if point.recall >= target_recall and (
            isnan(best) or point.false_positive_rate < best
        ):
            best = point.false_positive_rate
            chosen = candidate
    return best, chosen
