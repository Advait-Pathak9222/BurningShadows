"""Every published result must be produced by a committed command.

An external audit found seven result files in `docs/results/` that no command in the
repository could regenerate, while `benchmarks.md` presented them as reproducible. That is
the worst kind of evidence problem: the numbers may well have been correct, but nothing in
the repository could show it, and a reader has no way to tell a measurement from a typo.

These tests are the standing guard against it coming back.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "docs" / "results"

# Which command writes which artifact. A new file in docs/results/ must be added here, which
# means someone has to say out loud what regenerates it.
GENERATORS = {
    "results.json": "make report",
    "summary.md": "make report",
    "attention.json": "make attention",
    "attention.md": "make attention",
    "pii.json": "make pii-probe",
    "pii.md": "make pii-probe",
    "sensitivity.json": "make sensitivity",
    "sensitivity.md": "make sensitivity",
    "runtime.md": "make loadtest",
    "relearn.json": "make relearn",
    "relearn.md": "make relearn",
    # Needs a running Ollama, so it is off the demo path and off run_submission.sh. It is
    # still a published number, so it still has to name the command that reproduces it.
    "judge_probe.json": "make judge-probe",
    "judge_probe.md": "make judge-probe",
    "toxicchat.json": "make toxicchat",
    "aegis.json": "make benchmarks",
    "orbench.json": "make benchmarks",
    "beavertails.json": "make benchmarks",
    "ragtruth.json": "make benchmarks",
    "metrics_matrix.json": "make benchmarks",
    "benchmarks.md": "make benchmarks",
}

# Written by hand: narrative interpretation of the generated files above. These are allowed
# to exist, but they must not be the only home of a number.
NARRATIVE = {
    "aegis.md",
    "allocation-regime.md",
    "orbench.md",
    "ragtruth.md",
    "toxicchat.md",
}


def _tracked_results() -> list[Path]:
    return sorted(path for path in RESULTS.iterdir() if path.is_file())


def test_every_results_file_is_either_generated_or_declared_narrative() -> None:
    unaccounted = [
        path.name
        for path in _tracked_results()
        if path.name not in GENERATORS and path.name not in NARRATIVE
    ]
    assert not unaccounted, (
        "These files in docs/results/ have no committed generator and are not declared "
        f"narrative: {unaccounted}. Add a generator and list it in GENERATORS, mark the "
        "file as narrative interpretation, or delete it. Publishing a number that no "
        "command reproduces is what this test exists to prevent."
    )


def test_every_declared_generator_target_exists() -> None:
    """A stale entry here would let a deleted artifact keep its claim of reproducibility."""
    missing = [name for name in GENERATORS if not (RESULTS / name).exists()]
    assert not missing, f"declared as generated but absent: {missing}"


@pytest.mark.parametrize("name", sorted(n for n in GENERATORS if n.endswith(".json")))
def test_generated_json_parses(name: str) -> None:
    payload = json.loads((RESULTS / name).read_text(encoding="utf-8"))
    assert payload, f"{name} is empty"


def test_benchmarks_page_says_it_is_generated() -> None:
    """`benchmarks.md` is written by `make benchmarks` and must not be hand-edited."""
    text = (RESULTS / "benchmarks.md").read_text(encoding="utf-8")
    assert "Generated by `make benchmarks`" in text
    assert "Do not edit by hand" in text


def test_narrative_pages_point_at_the_command_that_produced_their_numbers() -> None:
    for name in sorted(NARRATIVE):
        path = RESULTS / name
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        assert "make " in text, (
            f"{name} quotes numbers but never names the command that regenerates them"
        )
